/**
 * optional —— 把「这一档可以没有」写进代码，而不是留在人的脑子里（IV-04）。
 *
 * 问题不是缺少 try/catch。真实 46 章跑批时，拟声词轮是裸 `await`，它一抛，
 * **已经决策好的 names/terms 连同 401 秒的真实开销一起作废**，作者只看到一句报错。
 * 一个锦上添花的环节不该有这种爆炸半径。
 *
 * 但更深的问题是：**可选性只存在于人的脑子里**。代码上，可选增强与骨干环节长得
 * 一模一样，下一个人照着旁边的写法加一轮，就又是一颗雷。反过来，各处零散的
 * try/catch 也在用五种不同的写法表达同一件事，读的人得逐个辨认哪个是刻意降级、
 * 哪个是随手吞掉。
 *
 * ## 判据：什么算「可选」
 *
 * **这一档没有，作者还能不能拿到可用的产物？**
 *
 * | 环节 | 判定 |
 * |---|---|
 * | 拟声词表缺失 | 翻译照常、术语表照常 → **可选** |
 * | 语气档案缺失 | 已有降级路径，译文仍可交付 → **可选** |
 * | 全书通读概览缺失 | 译文缺方位感但仍是完整译文 → **可选** |
 * | 段落门禁失败 | 译文结构对不上，产物不可用 → **不可选，必须失败** |
 * | 全书通读的裁决解析失败 | 不得当成「无问题」→ **不可选，必须失败**（fail-closed 是刻意设计） |
 * | 作者偏好编译失败 | 那是作者的明确指令，静默丢弃等于阳奉阴违 → **不可选，必须失败** |
 *
 * ## 反向风险
 *
 * 包过头比裸 await 更危险，因为它**静默**。`because` 之所以是必填参数，就是要求
 * 每个调用点当场回答上面那个问题——写不出为什么这一档可以没有，就说明它不可选。
 */

export interface OptionalOptions {
  /** 降级告知通道。没有它，"少了一档"这件事对作者不可见，等于没降级只是没做。 */
  onWarn?: (message: string) => void;
  /**
   * 为什么这一档可以没有。**必填**——它既是给读代码的人的答案，也随告警说给作者听，
   * 让「少了拟声词表」不至于被读成「翻译坏了」。
   */
  because: string;
}

/**
 * 跑一个可选环节。成功返回结果，失败发一条告警并返回 `null`。
 *
 * 返回 `null` 而不是空值（`[]` / `{}`）是有意的：调用方必须显式写出「没有这一档时用什么」，
 * 那一行代码就是它对降级后果的承认。
 */
export async function optional<T>(
  label: string,
  run: () => Promise<T>,
  options: OptionalOptions,
): Promise<T | null> {
  try {
    return await run();
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    options.onWarn?.(`${label}未完成，本次不产出该档（${options.because}）：${detail}`);
    return null;
  }
}
